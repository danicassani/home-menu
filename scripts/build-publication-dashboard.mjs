 "import { createClient } from 'npm:@supabase/supabase-js@2.119.0';\n"+handler+
 "\nDeno.serve(createPublicationHandler(createClient,{url:Deno.env.get('SUPABASE_URL')!,anon:Deno.env.get('SUPABASE_ANON_KEY')!,key:Deno.env.get('SUPABASE_SERVICE_ROLE_KEY')!}));\n";
const file=folder+'dashboard.ts';
if(process.argv.includes('--check')){if(readFileSync(file,'utf8')!==generated)throw new Error('Regenerate dashboard.ts');}
else writeFileSync(file,generated);
